
import streamlit as st
import pandas as pd
import joblib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL_PATH = ROOT / "model" / "iris_decision_tree.joblib"

st.set_page_config(
    page_title="Iris ML Predictor",
    page_icon="🌸",
    layout="centered"
)

@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)

model = load_model()

st.title("🌸 Iris Flower Classifier")
st.write("Enter flower measurements below and get a real-time prediction from a trained Decision Tree model.")

st.sidebar.header("Flower Measurements")

sepal_length = st.sidebar.slider("Sepal Length (cm)", 4.0, 8.0, 5.1, 0.1)
sepal_width = st.sidebar.slider("Sepal Width (cm)", 2.0, 4.5, 3.5, 0.1)
petal_length = st.sidebar.slider("Petal Length (cm)", 1.0, 7.0, 1.4, 0.1)
petal_width = st.sidebar.slider("Petal Width (cm)", 0.1, 2.5, 0.2, 0.1)

input_data = pd.DataFrame([{
    "sepal_length": sepal_length,
    "sepal_width": sepal_width,
    "petal_length": petal_length,
    "petal_width": petal_width
}])

prediction = model.predict(input_data)[0]
probabilities = model.predict_proba(input_data)[0]
classes = model.classes_

st.subheader("Input Values")
st.dataframe(input_data, use_container_width=True, hide_index=True)

st.subheader("Prediction")
st.success(f"Predicted Flower: **{prediction.title()}**")

st.subheader("Prediction Confidence")
confidence_df = pd.DataFrame({
    "Species": [c.title() for c in classes],
    "Probability": [f"{p:.2%}" for p in probabilities]
})
st.dataframe(confidence_df, use_container_width=True, hide_index=True)

st.info("The prediction is generated by the saved Decision Tree model using the four measurements above.")

st.caption("Built with Python, Scikit-Learn, Joblib, Pandas and Streamlit.")
